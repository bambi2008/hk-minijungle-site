export function getPlantSource(sourceId) {
  const source = plantSourceManifest[sourceId];
  if (!source) throw new Error(`Unknown plant source: ${sourceId}`);
  return source;
}

export function listAutomatablePlantSources() {
  return Object.values(plantSourceManifest).filter((source) => source.automation !== "disabled");
}
