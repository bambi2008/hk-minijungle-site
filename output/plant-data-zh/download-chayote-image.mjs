import {mkdir,writeFile} from "node:fs/promises";
import {createHash} from "node:crypto";
import assert from "node:assert/strict";
import {buildCommonsBatchUrl} from "../../tools/plant-import/enrich-wikimedia.mjs";
import {getPlantSource} from "../../tools/plant-import/source-manifest.mjs";
import {cachedJson,OUT} from "./import-vegetables.mjs";
const directory=`${OUT}/chayote-image`;
const clean=value=>String(value||"").replace(/<[^>]*>/g," ").replace(/&amp;/g,"&").replace(/&#39;/g,"'").replace(/\s+/g," ").trim();
await mkdir(`${directory}/media`,{recursive:true});
const title="File:Sechium edule - Fruits.jpg";
const payload=await cachedJson(buildCommonsBatchUrl([title]),`${directory}/raw`);
const page=payload.query?.pages?.find(p=>p.title===title),info=page?.imageinfo?.[0];
assert.ok(info);
const metadata=info.extmetadata;
const licence=clean(metadata?.LicenseShortName?.value).toUpperCase();
assert.ok(getPlantSource("wikimedia-commons").allowedLicences.includes(licence));
const creator=clean(metadata?.Artist?.value||metadata?.Credit?.value);
assert.ok(creator&&info.descriptionurl);
assert.ok(clean([page.title,metadata?.ImageDescription?.value].join(" ")).includes("Sechium edule"));
const url=new URL(info.thumburl||info.url);
assert.equal(url.protocol,"https:");assert.ok(["upload.wikimedia.org","thumb.wikimedia.org"].includes(url.hostname));
assert.equal(info.mime,"image/jpeg");
const response=await fetch(url,{redirect:"error",signal:AbortSignal.timeout(30000)});
assert.equal(response.status,200);
assert.equal((response.headers.get("content-type")||"").split(";")[0],"image/jpeg");
const data=Buffer.from(await response.arrayBuffer());
assert.ok(data.length<=8*1024*1024&&data.length>3);
assert.deepEqual([...data.subarray(0,3)],[255,216,255]);
await writeFile(`${directory}/media/gbif-species-2874612.jpg`,data);
const media={kind:"image",url:url.href,sourcePage:info.descriptionurl,creator,licence,licenceUrl:metadata?.LicenseUrl?.value||"",attribution:`${creator} · ${licence} · Wikimedia Commons`,sourceId:"wikimedia-commons",localPath:"media/gbif-species-2874612.jpg",sha256:createHash("sha256").update(data).digest("hex"),bytes:data.length,mimeType:info.mime,width:info.thumbwidth||info.width,height:info.thumbheight||info.height};
await writeFile(`${directory}/image-result.json`,JSON.stringify({recordId:"gbif-species:2874612",queryFile:title,media},null,2));
console.log(JSON.stringify({recordId:"gbif-species:2874612",licence,creator,bytes:data.length,sha256:media.sha256}));
