import {readFile,writeFile} from "node:fs/promises";
import {createHash} from "node:crypto";
import assert from "node:assert/strict";
import {collectPlantKnowledge} from "./collect-plant-knowledge.mjs";
import {enrichChinese} from "./enrich-chinese.mjs";
const sha=b=>createHash("sha256").update(b).digest("hex");
const root="data/plant-import/vegetables-priority";
const protectedFile="data/plant-import/us-gb-fr-translated-drafts/records-enriched.ndjson";
const before=sha(await readFile(protectedFile));
const results=JSON.parse(await readFile(`${root}/knowledge/collection-results.json`,"utf8"));
const files=results.filter(r=>r.status==="source-downloaded").map(r=>r.sourceFile);
const hashes=new Map(await Promise.all(files.map(async f=>[f,sha(await readFile(f))])));
let requests=0;globalThis.fetch=()=>{requests++;throw new Error("Unexpected network on cache resume");};
const knowledge=await collectPlantKnowledge({fetchEntities:false});
assert.equal(requests,0);assert.equal(knowledge.downloadedArticles,files.length);
for(const file of files)assert.equal(sha(await readFile(file)),hashes.get(file),file);
const chinese=await enrichChinese({inputs:[`${root}/vegetable-taxa.ndjson`],outDir:`${root}/chinese-enrichment`,resume:true,fetchImpl:globalThis.fetch});
assert.equal(chinese.status,"complete");assert.equal(chinese.networkRequestsThisRun,0);assert.equal(requests,0);assert.equal(sha(await readFile(protectedFile)),before);
const report={status:"passed",networkRequests:requests,stableSourcePackets:files.length,stableOriginalSha256:before,chineseProcessed:chinese.processed};
await writeFile(`${root}/cache-resume-integrity.json`,JSON.stringify(report,null,2));console.log(JSON.stringify(report));
